#!/usr/bin/env python3
"""bin2c.py IN OUT.c NAME: a file as `const unsigned char NAME[]` (4-byte
aligned) and `const unsigned int NAME_size` (the 3DS shader binaries)."""
import sys

src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, "rb").read()
lines = [f"/* generated by port/cmake/bin2c.py from {src.split('/')[-1]} */",
         f"const unsigned char {name}[] __attribute__((aligned(4))) = {{"]
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
lines.append("};")
lines.append(f"const unsigned int {name}_size = {len(data)};")
open(out, "w").write("\n".join(lines) + "\n")
